    /**
     * Generates a clean PDF for long NOVA answers with Topic, Date, Language, Formatted Markdown and Page Numbers.
     */
    fun generateNovaAnswerPdf(
        context: Context,
        topicTitle: String,
        contentMarkdown: String,
        language: String,
        sources: List<String> = emptyList()
    ): File {
        val reportDir = File(context.cacheDir, "reports").apply { mkdirs() }
        val cleanTopic = topicTitle.replace("[^a-zA-Z0-9_-]".toRegex(), "_").take(30)
        val outputFile = File(reportDir, "NOVA_Notes_${cleanTopic}_${System.currentTimeMillis()}.pdf")

        val pdfDocument = PdfDocument()
        var pageNumber = 1

        val paint = Paint(Paint.ANTI_ALIAS_FLAG)
        val textPaint = Paint(Paint.ANTI_ALIAS_FLAG)
        val dateStr = SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(Date())

        fun createPage(): Pair<PdfDocument.Page, Canvas> {
            val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
            val page = pdfDocument.startPage(pageInfo)
            val canvas = page.canvas
            canvas.drawColor(Color.WHITE)
            return Pair(page, canvas)
        }

        fun drawPageDecorations(canvas: Canvas, title: String, currentPage: Int) {
            // Header Top Bar
            paint.color = Color.rgb(15, 23, 42)
            canvas.drawRect(0f, 0f, PAGE_WIDTH.toFloat(), 44f, paint)

            paint.color = Color.rgb(99, 102, 241) // Indigo accent
            canvas.drawRect(0f, 44f, PAGE_WIDTH.toFloat(), 47f, paint)

            // Header Title
            textPaint.color = Color.WHITE
            textPaint.textSize = 11f
            textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            canvas.drawText("StudyMate AI • NOVA Academic Notes", MARGIN, 28f, textPaint)

            textPaint.color = Color.rgb(203, 213, 225)
            textPaint.textSize = 9.5f
            textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            val rightText = "$dateStr | $language"
            canvas.drawText(rightText, PAGE_WIDTH - MARGIN - textPaint.measureText(rightText), 28f, textPaint)

            // Footer
            paint.color = Color.rgb(241, 245, 249)
            canvas.drawRect(0f, PAGE_HEIGHT - 32f, PAGE_WIDTH.toFloat(), PAGE_HEIGHT.toFloat(), paint)

            textPaint.color = Color.rgb(100, 116, 139)
            textPaint.textSize = 8.5f
            canvas.drawText("Generated by NOVA Personal AI Study Coach", MARGIN, PAGE_HEIGHT - 12f, textPaint)

            val pageStr = "Page $currentPage"
            canvas.drawText(pageStr, PAGE_WIDTH - MARGIN - textPaint.measureText(pageStr), PAGE_HEIGHT - 12f, textPaint)
        }

        var (currentPage, canvas) = createPage()
        drawPageDecorations(canvas, topicTitle, pageNumber)
        var currentY = 70f

        // Title Header
        paint.color = Color.rgb(248, 250, 252)
        canvas.drawRoundRect(MARGIN, currentY, PAGE_WIDTH - MARGIN, currentY + 48f, 8f, 8f, paint)
        paint.style = Paint.Style.STROKE
        paint.strokeWidth = 1f
        paint.color = Color.rgb(226, 232, 240)
        canvas.drawRoundRect(MARGIN, currentY, PAGE_WIDTH - MARGIN, currentY + 48f, 8f, 8f, paint)
        paint.style = Paint.Style.FILL

        textPaint.color = Color.rgb(15, 23, 42)
        textPaint.textSize = 14f
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText(topicTitle.take(50), MARGIN + 12f, currentY + 22f, textPaint)

        textPaint.color = Color.rgb(100, 116, 139)
        textPaint.textSize = 9f
        textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Topic Dossier • $dateStr • Language: $language", MARGIN + 12f, currentY + 38f, textPaint)

        currentY += 64f

        // Body content paragraphs
        val lines = contentMarkdown.split("\n")
        for (rawLine in lines) {
            val trimmed = rawLine.trim()
            if (trimmed.isEmpty()) {
                currentY += 8f
                continue
            }

            if (currentY > PAGE_HEIGHT - 70f) {
                pdfDocument.finishPage(currentPage)
                pageNumber++
                val next = createPage()
                currentPage = next.first
                canvas = next.second
                drawPageDecorations(canvas, topicTitle, pageNumber)
                currentY = 65f
            }

            when {
                trimmed.startsWith("###") || trimmed.startsWith("##") || trimmed.startsWith("#") -> {
                    currentY += 6f
                    val heading = trimmed.removePrefix("#").removePrefix("#").removePrefix("#").trim()
                    textPaint.color = Color.rgb(30, 41, 59)
                    textPaint.textSize = 11.5f
                    textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                    drawWrappedText(canvas, heading, MARGIN, currentY, PAGE_WIDTH - (MARGIN * 2), textPaint, 14f)
                    currentY += 16f
                }
                trimmed.startsWith("-") || trimmed.startsWith("*") || trimmed.startsWith("•") -> {
                    val bulletText = "•  " + trimmed.substring(1).trim()
                    textPaint.color = Color.rgb(51, 65, 85)
                    textPaint.textSize = 9.5f
                    textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                    drawWrappedText(canvas, bulletText, MARGIN + 8f, currentY, PAGE_WIDTH - (MARGIN * 2) - 8f, textPaint, 13f)
                    currentY += 15f
                }
                else -> {
                    textPaint.color = Color.rgb(51, 65, 85)
                    textPaint.textSize = 9.5f
                    textPaint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                    drawWrappedText(canvas, trimmed, MARGIN, currentY, PAGE_WIDTH - (MARGIN * 2), textPaint, 13f)
                    currentY += 15f
                }
            }
        }

        pdfDocument.finishPage(currentPage)

        val fos = FileOutputStream(outputFile)
        pdfDocument.writeTo(fos)
        fos.flush()
        fos.close()
        pdfDocument.close()

        return outputFile
    }

    private fun drawWrappedText(canvas: Canvas, text: String, x: Float, startY: Float, maxWidth: Float, paint: Paint, lineHeight: Float) {
        val words = text.split(" ")
        var line = ""
        var currentY = startY

        for (word in words) {
            val testLine = if (line.isEmpty()) word else "$line $word"
            if (paint.measureText(testLine) > maxWidth) {
                canvas.drawText(line, x, currentY, paint)
                line = word
                currentY += lineHeight
            } else {
                line = testLine
            }
        }
        if (line.isNotEmpty()) {
            canvas.drawText(line, x, currentY, paint)
        }
    }
